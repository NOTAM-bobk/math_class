// Downloads the cover art for the imported online games and writes the map the
// catalog reads (src/lib/gameCovers.ts).
//
// The games themselves are served same-origin through /api/proxy, but their
// artwork lives on the game host, which school networks often block. Copying it
// into ./covers keeps the recent row and mosaic cards working on those networks.
//
// Usage: npm run build:covers   (re-runs only fetch covers that are missing)

import fs from "node:fs";
import path from "node:path";

const FEED_URL = "https://www.onlinegames.io/media/plugins/genGames/embed.json";
const CATALOG_PATH = "api/_catalog.json";
const COVER_DIR = "covers";
const OUT_PATH = "src/lib/gameCovers.ts";
const CONCURRENCY = 6;

const normalize = (value) => String(value || "").toLowerCase().replace(/[^a-z0-9]/g, "");
const extensionFor = (type) => {
  if (type.includes("png")) return "png";
  if (type.includes("webp")) return "webp";
  if (type.includes("gif")) return "gif";
  return "jpg";
};

async function main() {
  if (!fs.existsSync(CATALOG_PATH)) {
    throw new Error(`${CATALOG_PATH} is missing; run npm run build:catalog first.`);
  }
  const catalog = JSON.parse(fs.readFileSync(CATALOG_PATH, "utf8"));

  const response = await fetch(FEED_URL, { headers: { Accept: "application/json" } });
  if (!response.ok) throw new Error(`Cover feed returned ${response.status}`);
  const feed = await response.json();

  const byName = new Map();
  for (const entry of Array.isArray(feed) ? feed : []) {
    const key = normalize(entry?.title);
    if (key && entry?.image && !byName.has(key)) byName.set(key, entry);
  }

  fs.mkdirSync(COVER_DIR, { recursive: true });
  const existingFiles = fs.readdirSync(COVER_DIR);
  const covers = {};
  const stats = { downloaded: 0, reused: 0, failed: 0, unmatched: 0 };

  const queue = [];
  for (const game of catalog) {
    if (!game?.id) continue;
    if (!byName.has(normalize(game.name))) {
      // Games the feed does not list (the Flash archive, for example) still get
      // a cover when one has been captured into ./covers by hand.
      const base = String(game.id).replace(/[^a-z0-9._-]/gi, "-");
      const existing = existingFiles.find((file) => file.startsWith(`${base}.`));
      if (existing) {
        covers[game.id] = `/covers/${existing}`;
        stats.reused++;
      } else {
        stats.unmatched++;
      }
      continue;
    }
    queue.push(game);
  }

  async function download(game) {
    const base = String(game.id).replace(/[^a-z0-9._-]/gi, "-");
    const existing = existingFiles.find((file) => file.startsWith(`${base}.`));
    if (existing) {
      covers[game.id] = `/covers/${existing}`;
      stats.reused++;
      return;
    }
    try {
      const res = await fetch(byName.get(normalize(game.name)).image);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const buffer = Buffer.from(await res.arrayBuffer());
      if (buffer.length < 1024) throw new Error("file too small");
      const file = `${base}.${extensionFor(res.headers.get("content-type") || "")}`;
      fs.writeFileSync(path.join(COVER_DIR, file), buffer);
      covers[game.id] = `/covers/${file}`;
      stats.downloaded++;
    } catch (error) {
      stats.failed++;
      console.warn(`  ! ${game.name}: ${error.message}`);
    }
  }

  for (let index = 0; index < queue.length; index += CONCURRENCY) {
    await Promise.all(queue.slice(index, index + CONCURRENCY).map(download));
  }

  const entries = Object.keys(covers)
    .sort()
    .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(covers[id])},`)
    .join("\n");

  const source = `// Generated by scripts/build-game-covers.mjs — do not edit by hand.
// Cover art for games that ship one, keyed by game id and served from /covers.

export const GAME_COVERS: Record<string, string> = {
${entries}
};

/** Cover art for a game id, or "" when the game has none (the card then shows initials). */
export function gameCoverUrl(id: string): string {
  return GAME_COVERS[id] || "";
}
`;

  fs.writeFileSync(OUT_PATH, source);

  console.log(
    `Covers: ${Object.keys(covers).length} of ${catalog.length} games ` +
      `(${stats.downloaded} downloaded, ${stats.reused} already present, ${stats.failed} failed, ${stats.unmatched} without art)`
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
