// Builds catalog.json, the single list the app fetches at runtime and the
// server-side search route reads. The entries live in src/data/*, split into the
// hand-maintained games and the two imported feeds, so keeping them out of the
// client bundle does not make them harder to edit.
import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const outfile = path.join(os.tmpdir(), `polytrack-catalog-${Date.now()}.mjs`);

const result = await build({
  stdin: {
    contents: [
      'import { DEFAULT_GAMES } from "@/data/defaultGames";',
      'import { ONLINE_GAMES } from "@/data/onlineGames";',
      'import { HFMANOR_GAMES } from "@/data/hfmanorGames";',
      'import { CDN_GAMES } from "@/data/cdnGames";',
      "process.stdout.write(JSON.stringify([...DEFAULT_GAMES, ...ONLINE_GAMES, ...HFMANOR_GAMES, ...CDN_GAMES]));",
    ].join("\n"),
    resolveDir: root,
    loader: "tsx",
    sourcefile: "catalog-entry.tsx",
  },
  bundle: true,
  platform: "node",
  format: "esm",
  write: false,
  alias: { "@": path.join(root, "src") },
  logLevel: "silent",
});

fs.writeFileSync(outfile, result.outputFiles[0].text);

try {
  const json = execFileSync(process.execPath, [outfile], { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
  const games = JSON.parse(json);
  if (!Array.isArray(games) || games.length === 0) throw new Error("Catalog is empty");

  fs.writeFileSync(path.join(root, "catalog.json"), `${JSON.stringify(games)}\n`);
  // The search route reads the same list, so client and server never drift.
  fs.writeFileSync(path.join(root, "api", "_catalog.json"), `${JSON.stringify(games, null, 2)}\n`);
  console.log(`Wrote catalog.json and api/_catalog.json (${games.length} games)`);
} finally {
  fs.rmSync(outfile, { force: true });
}

// Stamp the build so the footer and Settings can show when the site last changed.
const stamp = new Date().toISOString();
fs.writeFileSync(
  path.join(root, "src", "lib", "buildInfo.ts"),
  `// Generated by scripts/export-catalog.mjs on every build. Do not edit by hand.\nexport const LAST_UPDATED_ISO = "${stamp}";\n`,
);
console.log(`Stamped build at ${stamp}`);


// Also write version.json so clients can check for updates on-demand.
const changelogText = fs.readFileSync(path.join(root, "src", "lib", "changelog.ts"), "utf8");
const verMatch = /SITE_VERSION\s*=\s*["']([^"']+)["']/.exec(changelogText);
const siteVersion = verMatch ? verMatch[1] : "1.7.2";

fs.writeFileSync(
  path.join(root, "version.json"),
  JSON.stringify(
    {
      version: siteVersion,
      buildIso: stamp,
      buildTime: Date.now(),
    },
    null,
    2
  ) + "\n"
);
console.log(`Wrote version.json (v${siteVersion} at ${stamp})`);
